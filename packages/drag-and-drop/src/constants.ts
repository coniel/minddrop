/**
 * How far a pointer has to travel, in pixels, for a press to count
 * as a drag rather than a click.
 */
export const DRAG_THRESHOLD = 4;

/**
 * Width, in pixels, of the zones along a scroll container's edges
 * which scroll it while a drag sits in them.
 */
export const SCROLL_EDGE_SIZE = 180;

/**
 * Scroll speed, in pixels per frame, at the deepest point of a
 * scroll container's edge zone and past its edge.
 */
export const SCROLL_MAX_SPEED = 48;
