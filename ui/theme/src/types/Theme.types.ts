// The resolved theme appearance value
export type ResolvedThemeVariant = 'light' | 'dark';

// The theme variant setting, picked by the user
export type ThemeVariant = 'light' | 'dark' | 'system';

// How strongly bright images are darkened while the dark theme is
// active, from '1' (subtlest) to '3' (strongest)
export type ImageDimming = 'off' | '1' | '2' | '3';
